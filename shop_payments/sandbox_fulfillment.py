"""Private, Sandbox-only fulfillment/inventory journal for BIG PAW food.

Not imported by the production backend, exposed over HTTP, or authorized to
issue real refunds, send notifications, or change Square fulfillment state.
Only an authenticated future operator interface may invoke these methods.
PII stays at Square; this database stores SKU counts and opaque order IDs.
"""
from __future__ import annotations

import sqlite3
import time
from contextlib import closing
from urllib.request import urlopen

from .retail_catalog import load_sale_catalog
from .sandbox_connector import SandboxOrderStore, SquareSandboxError
from .sandbox_reconcile import (
    retrieve_sandbox_shipment_status,
    retrieve_verified_sandbox_payment,
    verify_current_sandbox_payment,
)


class SandboxFulfillmentOps:
    """Atomic, fail-closed stock allocation after independent payment verification.

    NOTE: This cannot guarantee stock at checkout: paid orders compete for the
    currently available stock until a separate pre-checkout reservation flow is
    implemented. Do NOT expose the checkout publicly based on this module.
    """

    def __init__(self, order_store: SandboxOrderStore):
        self.order_store = order_store
        with closing(self._open()) as conn:
            conn.executescript("""
                CREATE TABLE IF NOT EXISTS food_stock (
                  sku TEXT PRIMARY KEY,
                  available INTEGER NOT NULL CHECK(available >= 0)
                );
                CREATE TABLE IF NOT EXISTS food_fulfillment (
                  order_id TEXT PRIMARY KEY,
                  state TEXT NOT NULL CHECK(state IN
                    ('address_review','stock_review','ready_to_pack',
                     'shipped','refund_review','refunded')),
                  stock_reserved INTEGER NOT NULL DEFAULT 0 CHECK(stock_reserved IN (0,1)),
                  updated_at INTEGER NOT NULL
                );
                CREATE TABLE IF NOT EXISTS food_operator_outbox (
                  order_id TEXT NOT NULL,
                  event_type TEXT NOT NULL,
                  created_at INTEGER NOT NULL,
                  PRIMARY KEY (order_id,event_type)
                );
            """)

    def _open(self):
        conn = sqlite3.connect(self.order_store.db_file, timeout=10, isolation_level=None)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA busy_timeout=10000")
        return conn

    @staticmethod
    def _emit(conn, order_id: str, event_type: str):
        conn.execute(
            "INSERT OR IGNORE INTO food_operator_outbox(order_id,event_type,created_at)"
            " VALUES (?,?,?)", (order_id, event_type, int(time.time())),
        )

    def set_stock(self, sku: str, available: int):
        """Trusted operator/test action only, NOT a public API."""
        if sku not in load_sale_catalog():
            raise ValueError("unknown retail SKU")
        if type(available) is not int or not 0 <= available <= 100000:
            raise ValueError("invalid stock count")
        with closing(self._open()) as conn:
            conn.execute(
                "INSERT INTO food_stock(sku,available) VALUES (?,?) "
                "ON CONFLICT(sku) DO UPDATE SET available=excluded.available",
                (sku, available),
            )

    def stock(self, sku: str) -> int:
        if sku not in load_sale_catalog():
            raise ValueError("unknown retail SKU")
        with closing(self._open()) as conn:
            row = conn.execute("SELECT available FROM food_stock WHERE sku=?", (sku,)).fetchone()
        return row["available"] if row else 0

    def state(self, order_id: str) -> str:
        snapshot = self.order_store.paid_order_snapshot(order_id)
        if snapshot is None:
            return "payment_not_verified"
        with closing(self._open()) as conn:
            row = conn.execute(
                "SELECT state FROM food_fulfillment WHERE order_id=?", (order_id,)
            ).fetchone()
        return row["state"] if row else "not_assessed"

    def assess_paid_order(self, order_id: str, *, token: str, opener=urlopen) -> str:
        """Read Square's shipping fields; reserve stock only for verified paid orders.

        Does not persist, print or expose shipping address, recipient or phone.
        A later authenticated operator screen must read address directly from
        Square; no postal labels are generated by this method.
        """
        snapshot = self.order_store.paid_order_snapshot(order_id)
        if snapshot is None:
            raise ValueError("payment is not verified or SKU snapshot is missing")
        shipment = retrieve_sandbox_shipment_status(
            snapshot["square_order_id"], token=token, opener=opener
        )
        if shipment["square_order_id"] != snapshot["square_order_id"]:
            raise SquareSandboxError("Square shipment ID mismatch")
        has_address = shipment["shipment_details_complete"] is True
        cart = snapshot["cart"]
        if not cart or any(sku not in load_sale_catalog() or
                           type(qty) is not int or qty <= 0 for sku, qty in cart.items()):
            raise ValueError("invalid saved SKU snapshot")
        with closing(self._open()) as conn:
            try:
                conn.execute("BEGIN IMMEDIATE")
                current = conn.execute(
                    "SELECT state FROM food_fulfillment WHERE order_id=?", (order_id,)
                ).fetchone()
                if current and current["state"] not in ("address_review", "stock_review"):
                    conn.execute("COMMIT")
                    return current["state"]
                if not has_address:
                    state = "address_review"
                else:
                    sufficient = all(
                        (lambda r: bool(r and r["available"] >= qty))(
                            conn.execute(
                                "SELECT available FROM food_stock WHERE sku=?", (sku,)
                            ).fetchone()
                        )
                        for sku, qty in cart.items()
                    )
                    state = "ready_to_pack" if sufficient else "stock_review"
                    if sufficient:
                        for sku, qty in cart.items():
                            result = conn.execute(
                                "UPDATE food_stock SET available=available-? "
                                "WHERE sku=? AND available>=?", (qty, sku, qty),
                            )
                            if result.rowcount != 1:
                                raise ValueError("stock changed during reservation")
                reserved = 1 if state == "ready_to_pack" else 0
                conn.execute(
                    "INSERT INTO food_fulfillment(order_id,state,stock_reserved,updated_at)"
                    " VALUES (?,?,?,?) ON CONFLICT(order_id) DO UPDATE SET "
                    "state=excluded.state,stock_reserved=excluded.stock_reserved,"
                    "updated_at=excluded.updated_at",
                    (order_id, state, reserved, int(time.time())),
                )
                self._emit(conn, order_id, state)
                conn.execute("COMMIT")
                return state
            except Exception:
                conn.execute("ROLLBACK")
                raise

    def mark_shipped(self, order_id: str, *, token: str, opener=urlopen) -> str:
        """Journal dispatch only after fresh Square payment AND address checks.

        No goods are shipped, payment is created or customer data saved here.
        A historical paid webhook is not proof against a later Square refund.
        """
        snapshot = self.order_store.paid_order_snapshot(order_id)
        if snapshot is None:
            raise ValueError("Previously verified paid Sandbox order required")
        verify_current_sandbox_payment(
            snapshot=snapshot, token=token, opener=opener
        )
        shipping = retrieve_sandbox_shipment_status(
            snapshot["square_order_id"], token=token, opener=opener
        )
        if (shipping.get("square_order_id") != snapshot["square_order_id"]
                or shipping.get("shipment_details_complete") is not True):
            raise ValueError("Shipping recipient needs fresh Square verification")
        with closing(self._open()) as conn:
            try:
                conn.execute("BEGIN IMMEDIATE")
                row = conn.execute(
                    "SELECT state FROM food_fulfillment WHERE order_id=?", (order_id,)
                ).fetchone()
                if row and row["state"] == "shipped":
                    conn.execute("COMMIT")
                    return "shipped"
                if not row or row["state"] != "ready_to_pack":
                    raise ValueError("shipment requires paid order, address and allocated stock")
                conn.execute(
                    "UPDATE food_fulfillment SET state='shipped',updated_at=? "
                    "WHERE order_id=?", (int(time.time()), order_id),
                )
                self._emit(conn, order_id, "shipped")
                conn.execute("COMMIT")
                return "shipped"
            except Exception:
                conn.execute("ROLLBACK")
                raise

    def request_refund_review(self, order_id: str) -> str:
        """Freeze unshipped fulfillment; DOES NOT issue or claim a refund."""
        with closing(self._open()) as conn:
            try:
                conn.execute("BEGIN IMMEDIATE")
                row = conn.execute(
                    "SELECT state FROM food_fulfillment WHERE order_id=?", (order_id,)
                ).fetchone()
                if not row or row["state"] in ("shipped", "refunded"):
                    raise ValueError("unshipped assessed order required")
                if row["state"] != "refund_review":
                    conn.execute(
                        "UPDATE food_fulfillment SET state='refund_review',updated_at=? "
                        "WHERE order_id=?", (int(time.time()), order_id),
                    )
                    self._emit(conn, order_id, "refund_review")
                conn.execute("COMMIT")
                return "refund_review"
            except Exception:
                conn.execute("ROLLBACK")
                raise

    def reconcile_full_refund(self, order_id: str, *, token: str, opener=urlopen) -> str:
        """Only confirm full refund after fresh Sandbox Payments API lookup.

        Refund initiation and partial-refund policy are deliberately NOT here.
        Stock is restored exactly once, and only for an unshipped order.
        """
        snapshot = self.order_store.paid_order_snapshot(order_id)
        if snapshot is None:
            raise ValueError("no verified payment reference")
        payment = retrieve_verified_sandbox_payment(
            snapshot["square_payment_id"], token=token, opener=opener
        )
        money = payment.get("amount_money")
        refunded = payment.get("refunded_money")
        expected = snapshot["amount_yen"]
        if (payment.get("status") != "COMPLETED"
                or payment.get("order_id") != snapshot["square_order_id"]
                or payment.get("location_id") != snapshot["square_location_id"]
                or not isinstance(money, dict)
                or money.get("currency") != "JPY"
                or type(money.get("amount")) is not int
                or money["amount"] != expected
                or not isinstance(refunded, dict)
                or refunded.get("currency") != "JPY"
                or type(refunded.get("amount")) is not int
                or refunded["amount"] != expected):
            raise ValueError("full refund is not verified by Square")
        with closing(self._open()) as conn:
            try:
                conn.execute("BEGIN IMMEDIATE")
                row = conn.execute(
                    "SELECT state,stock_reserved FROM food_fulfillment WHERE order_id=?",
                    (order_id,),
                ).fetchone()
                if row and row["state"] == "refunded":
                    conn.execute("COMMIT")
                    return "refunded"
                if not row or row["state"] != "refund_review":
                    raise ValueError("refunded state requires unshipped refund review")
                if row["stock_reserved"]:
                    for sku, qty in snapshot["cart"].items():
                        result = conn.execute(
                            "UPDATE food_stock SET available=available+? WHERE sku=?",
                            (qty, sku),
                        )
                        if result.rowcount != 1:
                            raise ValueError("original reserved inventory missing")
                conn.execute(
                    "UPDATE food_fulfillment SET state='refunded',stock_reserved=0,"
                    "updated_at=? WHERE order_id=?", (int(time.time()), order_id),
                )
                self._emit(conn, order_id, "refunded")
                conn.execute("COMMIT")
                return "refunded"
            except Exception:
                conn.execute("ROLLBACK")
                raise

    def operator_queue(self) -> list[dict]:
        """Non-PII events only; not yet connected to email or admin UI."""
        with closing(self._open()) as conn:
            rows = conn.execute(
                "SELECT order_id,event_type,created_at FROM food_operator_outbox "
                "ORDER BY created_at,order_id,event_type"
            ).fetchall()
        return [dict(row) for row in rows]
