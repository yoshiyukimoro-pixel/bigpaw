/* Detail gallery for the staging catalog only; never starts checkout. */
(() => {
  'use strict';
  const single = document.getElementById('single');
  const host = document.getElementById('detail');
  if (!single || single.hidden || !host) return;
  const id = new URLSearchParams(window.location.search).get('item');
  const rows = window.BIGPAW_SHOP_DETAIL_IMAGES?.[id];
  if (!Array.isArray(rows) || !rows.length) return;

  const section = document.createElement('section');
  section.className = 'shop-image-section';
  section.setAttribute('aria-label','メーカー提供の商品詳細画像');
  const heading = document.createElement('h2');
  heading.textContent = '写真でわかる商品の特徴';
  const intro = document.createElement('p');
  intro.className = 'shop-image-intro';
  intro.textContent = 'この商品専用の画像から順番に、ブランド共通の製法や特徴をご覧いただけます。画像をタップすると拡大します。';
  const list = document.createElement('div');
  list.className = 'shop-image-list';
  list.id = 'shopDetailImageList';
  const missing = document.createElement('p');
  missing.id = 'shopDetailImageMissing';
  missing.className = 'shop-image-missing';
  missing.hidden = true;
  missing.textContent = '商品詳細画像は現在準備中です。';
  const dialog = document.createElement('dialog');
  dialog.className = 'shop-image-viewer';
  dialog.setAttribute('aria-label','商品詳細画像の拡大表示');
  const closeForm = document.createElement('form');
  closeForm.method = 'dialog';
  const close = document.createElement('button');
  close.type = 'submit';
  close.className = 'shop-viewer-close';
  close.textContent = '閉じる ✕';
  closeForm.append(close);
  const large = document.createElement('img');
  large.className = 'shop-viewer-photo';
  large.alt = '';
  const largeCaption = document.createElement('p');
  largeCaption.className = 'shop-viewer-caption';
  dialog.append(closeForm,large,largeCaption);
  let settled=0,loaded=0;
  rows.forEach((row,index) => {
    if (!row || !/^assets\/shop-details\/(products\/[AOZC][0-9]{2}|shared\/(acana|orijen|ziwi|charm))\/[a-z0-9-]+\.webp$/.test(row.src)) return;
    const figure = document.createElement('figure');
    figure.className = 'shop-image-figure';
    figure.dataset.scope = row.scope;
    const button = document.createElement('button');
    button.type='button';
    button.className='shop-image-open';
    button.setAttribute('aria-label',row.caption+'を拡大');
    const img = document.createElement('img');
    img.alt = row.caption;
    img.loading='lazy';
    img.decoding='async';
    const caption = document.createElement('figcaption');
    const scope = document.createElement('span');
    scope.className='shop-image-scope'+(row.scope==='brand'?' is-shared':'');
    scope.textContent = row.scope==='brand'?'ブランド共通':'この商品の詳細';
    caption.append(scope,document.createTextNode(row.caption));
    button.append(img);
    button.addEventListener('click',()=>{
      if(!img.naturalWidth) return;
      large.src=img.currentSrc||img.src;
      large.alt=img.alt;
      largeCaption.textContent=caption.textContent.trim();
      dialog.showModal();
    });
    figure.append(button,caption);
    list.append(figure);
    let finished=false;
    const mark=ok=>{
      if(finished)return;
      finished=true;settled++;
      if(ok){loaded++;missing.hidden=true;} else figure.hidden=true;
      if(settled===rows.length && loaded===0) missing.hidden=false;
    };
    img.addEventListener('load',()=>mark(true),{once:true});
    img.addEventListener('error',()=>mark(false),{once:true});
    img.src=row.src;
  });
  section.append(heading,intro,list,missing);
  host.append(section,dialog);
})();
